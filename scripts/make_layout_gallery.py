"""Pictures and page of the layout catalog (plans/PLAN_LAYOUT_CATALOG.md, card L-08).

    python scripts/make_layout_gallery.py      # draws docs/reference/gallery/layouts/<name>.png

`fa reference` (scripts/make_reference.py) calls this module too: it writes
docs/reference/layouts.md from ``layouts_page`` and the pictures from
``draw_layouts``. Every public layout in ``fig_atlas.layouts`` has an example
in examples/layouts/<name>/ (config.yaml + script.py); the picture is that
example's ``build()``, so the page shows exactly what the example script draws.
"""
from __future__ import annotations

import ast
import importlib.util
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples" / "layouts"
PICTURES = ROOT / "docs" / "reference" / "gallery" / "layouts"
DPI = 150
HEADER = "<!-- generated by scripts/make_reference.py (fa reference); edit the code, not this page -->\n\n"


def layout_names() -> list[str]:
    """The public layouts, in the order ``fig_atlas.layouts.__all__`` gives them."""
    from fig_atlas import layouts
    return [n for n in layouts.__all__ if n not in ("Layout", "finish")]


def load_example(name: str):
    """examples/layouts/<name>/script.py as a module (its ``build()`` draws the figure)."""
    path = EXAMPLES / name / "script.py"
    spec = importlib.util.spec_from_file_location(f"layout_example_{name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def code_lines(path: Path) -> int:
    """Lines of code in a script: not blank, not a comment, not the module docstring."""
    text = path.read_text(encoding="utf-8")
    tree = ast.parse(text)
    skip = set()
    if ast.get_docstring(tree) is not None:
        doc = tree.body[0]
        skip = set(range(doc.lineno, doc.end_lineno + 1))
    return sum(1 for i, line in enumerate(text.splitlines(), start=1)
               if i not in skip and line.strip() and not line.strip().startswith("#"))


def draw_layouts() -> list[str]:
    """Draw every example's picture; remove pictures of layouts that no longer exist."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    PICTURES.mkdir(parents=True, exist_ok=True)
    names = layout_names()
    for name in names:
        with matplotlib.rc_context():
            matplotlib.rcdefaults()
            fig = load_example(name).build()
            fig.savefig(PICTURES / f"{name}.png", dpi=DPI, metadata={"Software": None})
            plt.close(fig)
    for stale in PICTURES.glob("*.png"):
        if stale.stem not in names:
            stale.unlink()
    return names


def _md(text: str) -> str:
    return text.replace("``", "`")


def _doc_lines(name: str) -> list[str]:
    """The docstring of the layout's module: summary, ASCII shape, then the usage notes."""
    from fig_atlas import layouts
    return (sys.modules[getattr(layouts, name).__module__].__doc__ or "").strip("\n").splitlines()


def _summary(name: str) -> str:
    return _md(_doc_lines(name)[0])


def _section(name: str) -> str:
    from fig_atlas import layouts
    fn = getattr(layouts, name)
    lines = _doc_lines(name)
    drawn = [i for i, ln in enumerate(lines) if ln.startswith("    ") and ln.strip()[:1] in "+|"]
    shape = [lines[i][4:] for i in drawn]
    body = "\n".join(lines[drawn[-1] + 1:]).strip()
    script = EXAMPLES / name / "script.py"
    call = re.search(r"layouts\.%s\([^\n]*\)" % name, script.read_text(encoding="utf-8")).group(0)
    return (f"## {name}\n\n{_summary(name)}\n\n```text\n" + "\n".join(shape) + "\n```\n\n"
            f"![{name}](gallery/layouts/{name}.png)\n\n"
            f"`{name}{inspect.signature(fn)}`\n\n"
            f"The example (`examples/layouts/{name}/`, script {code_lines(script)} lines of code) calls "
            f"`{call}`.\n\n{_md(body)}\n\n")


def layouts_page() -> str:
    names = layout_names()
    rows = "".join(f"| [{n}](#{n}) | {_summary(n)} | `examples/layouts/{n}/` "
                   f"| {code_lines(EXAMPLES / n / 'script.py')} |\n" for n in names)
    return (HEADER + "# Layout catalog\n\n"
            "A layout arranges the panels of a figure; the renderers draw them. Each layout below is a "
            "function in `fig_atlas.layouts` that turns the config's `figures:` block into named cells: draw "
            "each panel into `layout.cells[letter]`, then call `layouts.finish(fig, layout, fcfg)` to fit the "
            "panels into their cells and place the panel letters. Structure is code, values are config: every "
            "number a layout uses (ratios, gaps, padding, tag size) comes from `figures:` with a default.\n\n"
            "Each picture is drawn by the layout's example in `examples/layouts/<name>/` (a commented "
            "`config.yaml` and a short `script.py`), with the gallery's synthetic bundles as panels. Copy the "
            "example, keep the layout call and `layouts.finish`, and draw your own data in the cells. A shape "
            "not listed here starts from the closest example.\n\n"
            "| layout | shape | example | script (lines of code) |\n|---|---|---|---|\n" + rows + "\n"
            + "".join(_section(n) for n in names))


if __name__ == "__main__":
    print(f"drew {len(draw_layouts())} layout pictures in {PICTURES.relative_to(ROOT).as_posix()}/")
