# modules a script imports whole and calls through (``claims.record``)
MODULE_STYLE = {"fig_atlas.claims", "fig_atlas.stats", "fig_atlas.source_data"}


def api_object(ref: str):
    module, _, name = ref.partition(":")
    return getattr(importlib.import_module(module), name)


def _signature(obj, name: str) -> str:
    import inspect
    if not (inspect.isfunction(obj) or inspect.isclass(obj)):
        return name                                  # a constant
    sig = inspect.signature(obj)
    params = [p.replace(annotation=inspect.Parameter.empty) for p in sig.parameters.values() if p.name != "self"]
    return name + str(sig.replace(parameters=params, return_annotation=inspect.Signature.empty))


def api_doc(obj) -> str:
    import inspect
    if not (inspect.isfunction(obj) or inspect.isclass(obj) or isinstance(obj, property)):
        obj = type(obj)                              # a constant: its class says what it means
    return inspect.cleandoc(obj.__doc__ or "")


def api_page() -> str:
    from string import Template
    skeleton = Template((ROOT / "fig_atlas" / "templates" / "project_analysis.py.tmpl").read_text(encoding="utf-8"))
    skeleton = skeleton.safe_substitute(name="my-project", date="<date>", slug="main",
                                        config="configs/config_my-project.yaml")
    out = [HEADER, "# Python reference\n\n",
           "The functions an analysis script or figure spec calls, by task. Everything else -- building, "
           "checking, promoting -- is a command ([Command reference](cli.md)); renderer parameters are in the "
           "[Config reference](config.md) and a picture of every plot in the [gallery](gallery.md).\n\n",
           "A new project's script (`fa new project`) already uses the common ones:\n\n",
           "```python\n", skeleton.rstrip("\n"), "\n```\n\n", "## Contents\n\n"]
    out += [f"- [{title}](#{title.lower().replace(' ', '-')})\n" for title, _, _ in API]
    for title, intro, entries in API:
        out.append(f"\n## {title}\n\n{intro}\n")
        for entry in entries:
            ref, members = entry if isinstance(entry, tuple) else (entry, [])
            module, _, name = ref.partition(":")
            obj = api_object(ref)
            if module in MODULE_STYLE:                   # used as claims.record(...), stats.stars(...)
                parent, _, short = module.rpartition(".")
                name, imp = f"{short}.{name}", f"from {parent} import {short}"
            else:
                imp = f"from {module} import {name}"
            out.append(f"\n### `{name}`\n\n`{imp}`\n\n"
                       f"```python\n{_signature(obj, name)}\n```\n\n{api_doc(obj)}\n")
            if members:
                out.append("\n")
            for m in members:
                attr = obj.__dict__[m]
                label = f"{name}.{m}" if isinstance(attr, property) else _signature(attr, f"{name}.{m}")
                out.append(f"- **`{label}`** -- {' '.join(api_doc(attr).split())}\n")
    return "".join(out)


# ---------------------------------------------------------------- config.md --
def _type(t) -> str:
    if isinstance(t, tuple):
        return "one of " + ", ".join(f"`{c}`" for c in t)
    return {float: "number", int: "integer", bool: "true / false", str: "text", list: "list", dict: "mapping",
            "color": "colour", "cmap": "colormap"}.get(t, getattr(t, "__name__", str(t)))


def _default(d) -> str:
    from fig_atlas.schema import CODE_DEFAULT, StyleRef
    if d is CODE_DEFAULT:
        return "computed"
    if isinstance(d, StyleRef):
        return f"style `{d.path}` (else `{d.fallback}`)"
    if d is None:
        return "auto"
    return f"`{d}`"


def config_page() -> str:
    from fig_atlas import recipes
    from fig_atlas.renderer_registry import available
    rows = [r for r in available() if not r["source"].startswith("recipe")]
    out = [HEADER, "# Config reference: renderer parameters\n\n",
           "The keys a `plots.<panel>` block of a project config can hold, per renderer, from each renderer's "
           "`SCHEMA` (the same descriptions `fa ingest bundle` and `fa param scaffold` write into configs). "
           "*auto* means unset: the renderer decides (e.g. axis limits from the data); *computed* means the "
           "renderer derives it from other values. Units: pt = points (1 pt = 0.35 mm), mm on the page, "
           "data coords = the axis's own units.\n\n",
           "| Plot name | Where | Parameters |\n|---|---|---|\n"]
    sections = []
    for r in rows:
        module, _, func = r["function"].partition(":")
        fn = getattr(importlib.import_module(module), func)
        schema = getattr(fn, "SCHEMA", None) or getattr(sys.modules[fn.__module__], "SCHEMA", None)
        n = len(schema.all()) if schema else 0
        out.append(f"| [`{r['name']}`](#{r['name']}) | {r['source']} | {n or 'no schema'} |\n")
        if not schema:
            continue
        sec = [f"\n## {r['name']}\n\n`{r['function']}`\n\n",
               "| Key | Type | Default | Unit | What it does |\n|---|---|---|---|---|\n"]
        for key, p in schema.all().items():
            what = p.role + (f" — {p.tune}" if p.tune else "")
            sec.append(f"| `{key}` | {_cell(_type(p.type))} | {_cell(_default(p.default))} | {_cell(p.unit)} | "
                       f"{_cell(what)} |\n")
        sections.append("".join(sec))
    out += sections
    found = recipes.all_recipes()
    if found:
        out.append("\n## Recipes\n\nA recipe is a core shape with a field's defaults and parameter names; "
                   "`fig_atlas.render(\"<name>\", ...)` draws it.\n\n| Recipe | Renderer | Defaults |\n|---|---|---|\n")
        for name, rec in sorted(found.items()):
            defaults = ", ".join(f"`{k}: {v}`" for k, v in sorted(rec.defaults.items()))
            out.append(f"| `{name}` | `{rec.renderer}` | {_cell(defaults)} |\n")
    return "".join(out)


# --------------------------------------------------------------- gallery.md --
def _cases():
    sys.path.insert(0, str(ROOT / "tests" / "renderers"))
    spec = importlib.util.spec_from_file_location("gallery_cases", ROOT / "tests" / "renderers" / "cases.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.CASES


def examples() -> list[Path]:
    return sorted(p for p in EXAMPLES.iterdir() if (p / "metadata" / "metadata.yaml").is_file()) \
        if EXAMPLES.is_dir() else []


def _example_section(bundle: Path) -> str:
    from fig_atlas.contracts import contract_for
    import yaml
    meta_text = (bundle / "metadata" / "metadata.yaml").read_text(encoding="utf-8")
    meta = yaml.safe_load(meta_text) or {}
    c = contract_for(meta.get("plot_type"))
    name = bundle.name
    inputs = sorted(f.name for f in (bundle / "inputs").iterdir())
    return (f"### {name}\n\n{c.title if c else ''}\n\n![{name}](gallery/examples/{name}.png)\n\n"
            f"Inputs: {', '.join(f'`{f}`' for f in inputs)}. `metadata/metadata.yaml`:\n\n"
            f"```yaml\n{meta_text.rstrip()}\n```\n\n"
            "Use it (in your project repository; `<fig-atlas>` is where fig-atlas is cloned):\n\n"
            "```bash\n"
            f"cp -r <fig-atlas>/examples/gallery/{name} raw_data/<project>/\n"
            f"fa bundle check raw_data/<project>/{name}\n"
            f"fa ingest bundle raw_data/<project>/{name} --project <project>\n"
            "fa build <project> --preflight\n"
            "```\n\n")


def gallery_page(cases) -> str:
    out = [HEADER, "# Renderer gallery\n\n",
           "## Start from an example (no code)\n\n",
           "Each picture below is drawn from a small synthetic data bundle in `examples/gallery/`, exactly "
           "as `fa ingest bundle` would draw it, at single-column size (85 mm). Pick the picture closest to "
           "the figure you need, copy its folder, replace `inputs/data.csv` with your table -- same column "
           "names, or name yours in `plot_params` -- and run the commands under it. The config block "
           "`fa ingest bundle` writes lists every setting with its unit and what it changes "
           "([config reference](config.md)). A test builds every example and checks it with preflight.\n\n"]
    out += [_example_section(b) for b in examples()]
    out.append("## Every renderer\n\n"
               "One example per renderer, drawn from small synthetic data by the renderer snapshot tests "
               "(`tests/renderers/cases.py`). Parameters for each are in the [config reference](config.md).\n\n")
    for name in sorted(cases):
        out.append(f"### {name}\n\n![{name}](gallery/{name}.png)\n\n")
    return "".join(out)


def draw_examples() -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from fig_atlas.bundle_figure import draw_bundle
    out = GALLERY / "examples"
    out.mkdir(parents=True, exist_ok=True)
    names = set()
    for bundle in examples():
        with matplotlib.rc_context():
            matplotlib.rcdefaults()
            plt.rcParams.update(EXAMPLE_RC)
            fig = draw_bundle(bundle, root=ROOT)
            fig.savefig(out / f"{bundle.name}.png", dpi=200, metadata={"Software": None})
            plt.close(fig)
        names.add(bundle.name)
    for stale in out.glob("*.png"):
        if stale.stem not in names:
            stale.unlink()


def draw_gallery(cases) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    GALLERY.mkdir(parents=True, exist_ok=True)
    for name in sorted(cases):
        with matplotlib.rc_context():
            matplotlib.rcdefaults()
            fig = cases[name]()
            fig.savefig(GALLERY / f"{name}.png", dpi=110, bbox_inches="tight", metadata={"Software": None})
            plt.close(fig)
    for stale in GALLERY.glob("*.png"):
        if stale.stem not in cases:
            stale.unlink()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a page is out of date")
    args = ap.parse_args()
    cases = _cases()
    pages = {REF / "cli.md": cli_page(), REF / "api.md": api_page(), REF / "config.md": config_page(),
             REF / "gallery.md": gallery_page(cases)}
    if args.check:
        stale = [p.relative_to(ROOT).as_posix() for p, text in pages.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        missing = sorted(n for n in cases if not (GALLERY / f"{n}.png").is_file())
        missing += sorted(f"examples/{b.name}" for b in examples()
                          if not (GALLERY / "examples" / f"{b.name}.png").is_file())
        for s in stale:
            print(f"out of date: {s}")
        for m in missing:
            print(f"missing gallery picture: docs/reference/gallery/{m}.png")
        if stale or missing:
            print("run `fa reference` (python scripts/make_reference.py) and commit the result")
            return 1
        print("reference pages are up to date")
        return 0
    REF.mkdir(parents=True, exist_ok=True)
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    draw_gallery(cases)
    draw_examples()
    print(f"wrote {len(cases)} gallery pictures and {len(examples())} example pictures in docs/reference/gallery/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
