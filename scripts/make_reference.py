"""Reference pages generated from the code, so they cannot go stale (roadmap 8.3).

    python scripts/make_reference.py            # writes the pages below (and the gallery images)
    python scripts/make_reference.py --check    # exit 1 if a page is out of date (CI)

- docs/reference/cli.md      every `fa` command and option, from the CLI parser
- docs/reference/config.md   every renderer parameter (type, default, unit, what it does), from
                             the renderers' SCHEMA; and the recipes with their defaults
- docs/reference/gallery.md  one picture per renderer case of the snapshot tests
                             (tests/renderers/cases.py), images in docs/reference/gallery/

The pictures are not compared byte for byte by --check (fonts differ between
machines); --check makes sure every case has a picture and the page lists them.
"""
from __future__ import annotations

import argparse
import importlib
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "docs" / "reference"
GALLERY = REF / "gallery"
HEADER = "<!-- generated by scripts/make_reference.py (fa reference); edit the code, not this page -->\n\n"


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


# ------------------------------------------------------------------- cli.md --
def cli_page() -> str:
    from fig_atlas.cli import PASSTHROUGH, build_parser
    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in sub._choices_actions}
    out = [HEADER, "# Command reference (`fa`)\n\n",
           "Every command of the `fa` tool. `fa <command> --help` shows the same. Commands that change files "
           "accept `--dry-run` (show the changes, write nothing); `--json` prints machine-readable results "
           "(what AI agents read through `fa mcp`). Exit codes: 0 success, 1 a build or check failed, "
           "2 usage or configuration error.\n\n",
           "| Command | What it does |\n|---|---|\n"]
    names = sorted(sub.choices)
    out += [f"| [`fa {n}`](#fa-{n}) | {_cell(helps.get(n) or '')} |\n" for n in names]
    for n in names:
        p = sub.choices[n]
        out.append(f"\n## fa {n}\n\n{helps.get(n) or ''}\n\n")
        if n in PASSTHROUGH:
            out.append(f"Runs `{PASSTHROUGH[n][0]}`; its own options: `fa {n} --help`.\n")
            continue
        usage = " ".join(p.format_usage().split())
        out.append(f"```\n{usage.replace('usage: ', '')}\n```\n\n")
        rows = []
        for a in p._actions:
            if isinstance(a, argparse._HelpAction):
                continue
            name = ", ".join(a.option_strings) or a.dest
            choices = f" One of: {', '.join(map(str, a.choices))}." if a.choices else ""
            default = (f" Default: `{a.default}`." if a.default not in (None, False, argparse.SUPPRESS, [])
                       and a.option_strings else "")
            rows.append(f"| `{name}` | {_cell((a.help or '') + choices + default)} |\n")
        if rows:
            out += ["| Argument | Meaning |\n|---|---|\n", *rows]
    return "".join(out)


# ---------------------------------------------------------------- config.md --
def _type(t) -> str:
    if isinstance(t, tuple):
        return "one of " + ", ".join(f"`{c}`" for c in t)
    return {float: "number", int: "integer", bool: "true / false", str: "text", list: "list", dict: "mapping",
            "color": "colour", "cmap": "colormap"}.get(t, getattr(t, "__name__", str(t)))


def _default(d) -> str:
    from fig_atlas.schema import CODE_DEFAULT, StyleRef
    if d is CODE_DEFAULT:
        return "computed"
    if isinstance(d, StyleRef):
        return f"style `{d.path}` (else `{d.fallback}`)"
    if d is None:
        return "auto"
    return f"`{d}`"


def config_page() -> str:
    from fig_atlas import recipes
    from fig_atlas.renderer_registry import available
    rows = [r for r in available() if not r["source"].startswith("recipe")]
    out = [HEADER, "# Config reference: renderer parameters\n\n",
           "The keys a `plots.<panel>` block of a project config can hold, per renderer, from each renderer's "
           "`SCHEMA` (the same descriptions `fa ingest bundle` and `fa param scaffold` write into configs). "
           "*auto* means unset: the renderer decides (e.g. axis limits from the data); *computed* means the "
           "renderer derives it from other values. Units: pt = points (1 pt = 0.35 mm), mm on the page, "
           "data coords = the axis's own units.\n\n",
           "| Plot name | Where | Parameters |\n|---|---|---|\n"]
    sections = []
    for r in rows:
        module, _, func = r["function"].partition(":")
        fn = getattr(importlib.import_module(module), func)
        schema = getattr(fn, "SCHEMA", None) or getattr(sys.modules[fn.__module__], "SCHEMA", None)
        n = len(schema.all()) if schema else 0
        out.append(f"| [`{r['name']}`](#{r['name']}) | {r['source']} | {n or 'no schema'} |\n")
        if not schema:
            continue
        sec = [f"\n## {r['name']}\n\n`{r['function']}`\n\n",
               "| Key | Type | Default | Unit | What it does |\n|---|---|---|---|---|\n"]
        for key, p in schema.all().items():
            what = p.role + (f" — {p.tune}" if p.tune else "")
            sec.append(f"| `{key}` | {_cell(_type(p.type))} | {_cell(_default(p.default))} | {_cell(p.unit)} | "
                       f"{_cell(what)} |\n")
        sections.append("".join(sec))
    out += sections
    found = recipes.all_recipes()
    if found:
        out.append("\n## Recipes\n\nA recipe is a core shape with a field's defaults and parameter names; "
                   "`fig_atlas.render(\"<name>\", ...)` draws it.\n\n| Recipe | Renderer | Defaults |\n|---|---|---|\n")
        for name, rec in sorted(found.items()):
            defaults = ", ".join(f"`{k}: {v}`" for k, v in sorted(rec.defaults.items()))
            out.append(f"| `{name}` | `{rec.renderer}` | {_cell(defaults)} |\n")
    return "".join(out)


# --------------------------------------------------------------- gallery.md --
def _cases():
    sys.path.insert(0, str(ROOT / "tests" / "renderers"))
    spec = importlib.util.spec_from_file_location("gallery_cases", ROOT / "tests" / "renderers" / "cases.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.CASES


def gallery_page(cases) -> str:
    out = [HEADER, "# Renderer gallery\n\n",
           "One example per renderer, drawn from small synthetic data by the renderer snapshot tests "
           "(`tests/renderers/cases.py`). Parameters for each are in the [config reference](config.md).\n\n"]
    for name in sorted(cases):
        out.append(f"## {name}\n\n![{name}](gallery/{name}.png)\n\n")
    return "".join(out)


def draw_gallery(cases) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    GALLERY.mkdir(parents=True, exist_ok=True)
    for name in sorted(cases):
        with matplotlib.rc_context():
            matplotlib.rcdefaults()
            fig = cases[name]()
            fig.savefig(GALLERY / f"{name}.png", dpi=110, bbox_inches="tight", metadata={"Software": None})
            plt.close(fig)
    for stale in GALLERY.glob("*.png"):
        if stale.stem not in cases:
            stale.unlink()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a page is out of date")
    args = ap.parse_args()
    cases = _cases()
    pages = {REF / "cli.md": cli_page(), REF / "config.md": config_page(), REF / "gallery.md": gallery_page(cases)}
    if args.check:
        stale = [p.relative_to(ROOT).as_posix() for p, text in pages.items()
                 if not p.is_file() or p.read_text(encoding="utf-8") != text]
        missing = sorted(n for n in cases if not (GALLERY / f"{n}.png").is_file())
        for s in stale:
            print(f"out of date: {s}")
        for m in missing:
            print(f"missing gallery picture: docs/reference/gallery/{m}.png")
        if stale or missing:
            print("run `fa reference` (python scripts/make_reference.py) and commit the result")
            return 1
        print("reference pages are up to date")
        return 0
    REF.mkdir(parents=True, exist_ok=True)
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    draw_gallery(cases)
    print(f"wrote {len(cases)} gallery pictures in docs/reference/gallery/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
