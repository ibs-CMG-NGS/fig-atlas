def cmd_requests(args) -> int:
    ev = _evidence_module()
    from fig_atlas.provenance import published_records
    if args.sync:
        added = ev.sync(REQUESTS_DIR)
        print(f"{REQUESTS_DIR.relative_to(ROOT)}: front matter drafted for {len(added)} request(s)"
              + "".join(f"\n  {p.name}" for p in added)
              + ("\n  review status/delivered/derived in each (drafted from the Status and Delivery lines)" if added else ""))
    rows = ev.ledger(ROOT, ev.load_requests(REQUESTS_DIR), published_records(ROOT))
    if args.json:
        print(json.dumps(rows, indent=1, ensure_ascii=False))
        return 0
    for r in rows:
        used = (f"integrated: {len(r['integrated'])} figure(s)" if r["integrated"] else "not read by any published figure")
        if r["mentioned_by"]:
            used += f"; named files read by {len(r['mentioned_by'])} more"
        print(f"{r['status']:<11} {r['date'] or '':<10}  {r['request']}  -- {used}")
        for m in r["missing"]:
            print(f"            delivered path not found: {m}")
        for s in r["superseded_by"]:
            print(f"            superseded by {s}")
    no_fm = sum(1 for r in rows if r["status"] == "(no front matter)")
    if no_fm:
        print(f"\n{no_fm} request(s) without front matter; `fa storyline requests --sync` drafts it")
    return 0


def _evidence_targets(arg: str, md: Path) -> list[tuple[str, str, Path | None]]:
    """(label, project, published PDF or None) for a slot name or a project."""
    cm = _compile_module()
    story = cm.parse_storyline_md(md)
    hits = [f for f in story["figures"] if f["role"].lower() == arg.lower()] or \
        [f for f in story["figures"] if f["project"] == arg]
    if hits:
        return [(f["role"], f["project"], cm.find_figure_pdf(f["project"], f["figure_number"])) for f in hits]
    from fig_atlas import get_config
    p = find_project(ROOT, arg)                      # any project, in a storyline or not
    pdfs = sorted(get_config(p.config).figures_root.glob("figure_*/figure_*.pdf"))
    return [(p.name, p.name, pdf) for pdf in pdfs] or [(p.name, p.name, None)]


def cmd_evidence(args) -> int:
    ev = _evidence_module()
    sn = _snapshot_module()
    from fig_atlas.provenance import HashCache, check_freshness
    md = _plan(args.plan)
    requests = ev.load_requests(REQUESTS_DIR)
    by_name = {r["name"]: r for r in requests}
    records = ev.revision_records(_compile_module().storyline_yaml_path(md).parent / "revisions")
    try:
        targets = _evidence_targets(args.target, md)
    except ProjectError as exc:
        print(f"{args.target}: not a slot of {md.name} or a project ({exc})")
        return 2
    cache = HashCache(ROOT)
    out = []
    for label, project, pdf in targets:
        entry = {"slot": label, "project": project, "figure": None, "fresh": None, "inputs": [], "requests": [],
                 "revisions": sorted({r["id"] for r in records if project in r["figures"]})}
        rec_path = sn.provenance_path(pdf) if pdf else None
        if rec_path and rec_path.is_file():
            rec = json.loads(rec_path.read_text(encoding="utf-8"))
            entry.update(figure=pdf.relative_to(ROOT).as_posix(), built=(rec.get("run") or {}).get("finished"),
                         fresh=not check_freshness(ROOT, rec, cache),
                         inputs=ev.figure_evidence(ROOT, rec, requests, cache))
        names = sorted({q["request"] for i in entry["inputs"] for q in i["requests"] if q["how"] == "declared"})
        entry["named_in"] = sorted({q["request"] for i in entry["inputs"] for q in i["requests"]} - set(names))
        for n in names:
            fm = by_name[n]["front_matter"] or {}
            entry["requests"].append({"request": n, "status": fm.get("status"), "date": fm.get("date"),
                                      "revisions": sorted({r["id"] for r in records if n in r["requests"]})})
        out.append(entry)
    cache.save()
    if args.json:
        print(json.dumps(out, indent=1, ensure_ascii=False, default=str))
        return 0
    for e in out:
        print(f"{e['slot']} -> {e['project']}")
        if not e["figure"]:
            print("  no published figure with a provenance record; build it with `fa build`\n")
            continue
        print(f"  figure   {e['figure']}  built {e['built']}  [{'fresh' if e['fresh'] else 'STALE'}]")
        print(f"  data read ({len(e['inputs'])} raw_data file(s)):")
        for i in e["inputs"]:
            up = (i.get("bundle") or {}).get("app_version")
            state = {True: "", False: "  CHANGED since the figure was built", None: "  MISSING now"}[i["current"]]
            print(f"    {i['path']}{f'  (upstream: {up})' if up else ''}{state}")
            for q in i["requests"]:
                if q["how"] == "declared":
                    print(f"        <- {q['request']}")
        print("  data requests that delivered it:" if e["requests"] else "  data requests that delivered it: none on record")
        for q in e["requests"]:
            revs = f"; revisions {', '.join(q['revisions'])}" if q["revisions"] else ""
            print(f"    {q['request']}  {q['status']} {q['date'] or ''}{revs}")
        if e["named_in"]:
            print(f"  also named in (context, not a delivery): {', '.join(e['named_in'])}")
        untracked = sum(1 for i in e["inputs"] if not any(q["how"] == "declared" for q in i["requests"]))
        if untracked:
            print(f"  {untracked} file(s) with no delivering request on record (delivered before the ledger, or made here)")
        if e["revisions"]:
            print(f"  revisions naming this project: {', '.join(e['revisions'])}")
        print()
    return 0


