def cmd_new(args) -> int:
    topic = args.topic
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", topic):
        print(f"fa: storyline name {topic!r}: use lower-case letters, digits and '-'", file=sys.stderr)
        return 1
    yaml_path = ROOT / "docs" / "storylines" / topic / "storyline.yaml"
    plan_path = ROOT / "docs" / "storylines" / f"figure_plan_{topic}.md"
    if yaml_path.exists() or plan_path.exists():
        print(f"fa: storyline {topic!r} already exists ({yaml_path.relative_to(ROOT).as_posix()})", file=sys.stderr)
        return 1
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    yaml_path.write_text(NEW_YAML.format(topic=topic, narrative=args.narrative or "<one paragraph: the paper's argument>"),
                         encoding="utf-8")
    plan_path.write_text(NEW_PLAN.format(topic=topic, title=args.title or topic).replace("storyline/" + topic, topic),
                         encoding="utf-8")
    for p in (yaml_path, plan_path):
        print(f"create  {p.relative_to(ROOT).as_posix()}")
    print("note: add each paper figure to figures: in storyline.yaml, then `fa storyline registry` and "
          "`fa storyline check`; `fa storyline compile --strict` builds the compendium")
    return 0


# ---------------------------------------------------------------------- check --
def cmd_check(args) -> int:
    mod = _compile_module()
    md = _plan(args.plan)
    story = mod.parse_storyline_md(md)
    problems = []
    if story.get("source") != "yaml":
        problems.append(f"no {mod.storyline_yaml_path(md).relative_to(ROOT)}; run `fa storyline init`")
    # The VS Code build dropdown is optional: checked only where .vscode/tasks.json exists.
    tasks_file = ROOT / ".vscode" / "tasks.json"
    selector = None
    if tasks_file.is_file():
        tasks = json.loads(tasks_file.read_text(encoding="utf-8"))
        selector = set(next(i for i in tasks["inputs"] if i["id"] == "projectSelector")["options"])
    for f in story["figures"]:
        name, n = f["project"], int(f["figure_number"] or 1)
        try:
            p = find_project(ROOT, name)
        except ProjectError as exc:
            problems.append(f"{f['role']}: {exc}")
            continue
        if p.archived:
            problems.append(f"{f['role']}: {name} is archived but assigned to a slot")
        if not (p.analysis_script and (ROOT / p.analysis_script).is_file()):
            problems.append(f"{f['role']}: analysis script {p.analysis_script} missing")
        if not _spec_file(name, n):
            problems.append(f"{f['role']}: figure_specs/**/figure_{n:02d}_{name}.py missing")
        if selector is not None and name not in selector:
            problems.append(f"{f['role']}: {name} missing from .vscode/tasks.json projectSelector")
    for name in story.get("retired", []):
        try:
            p = find_project(ROOT, name)
            if not p.archived:
                problems.append(f"retired {name}: config is not under configs/<domain>/archive/")
        except ProjectError as exc:
            problems.append(f"retired {name}: {exc}")
        if selector is not None and name in selector:
            problems.append(f"retired {name} still in .vscode/tasks.json projectSelector")
    for t in story["tables"]:
        if t.get("generator") and not (ROOT / t["generator"]).is_file():
            problems.append(f"{t['role']}: generator {t['generator']} missing")
    text = md.read_text(encoding="utf-8")
    if _replace_registry(text, registry_table(md, story)) != text:
        problems.append(f"{md.name}: Master Mapping Registry table is out of date; run `fa storyline registry`")
    for p in problems:
        print(f"PROBLEM  {p}")
    print(f"{md.relative_to(ROOT)}: {len(story['figures'])} figures, {len(story['tables'])} tables, "
          f"{len(story.get('retired', []))} retired -- {'OK' if not problems else f'{len(problems)} problem(s)'}")
    return 1 if problems else 0


