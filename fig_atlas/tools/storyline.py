def cmd_snapshots(args) -> int:
    sn = _snapshot_module()
    md = _plan(args.plan)
    snaps = sn.list_snapshots(ROOT, md)
    for d in snaps:
        rev = json.loads((d / "revision.json").read_text(encoding="utf-8"))
        h = rev.get("health")
        n_prov = sum(1 for f in rev.get("figures", []) if f.get("provenance"))
        print(f"{d.name}  compiled {rev.get('compiled', '?')}  commit {rev.get('git_commit') or '?'}"
              f"{' (uncommitted storyline)' if rev.get('storyline_uncommitted') else ''}  "
              f"{len(rev.get('figures', []))} figures, {n_prov} with provenance"
              + (f"  [{sn.health_line(h)}]" if h else "  [pre-S.3 snapshot: no provenance]"))
    if not snaps:
        print(f"no snapshots under outputs/storylines/{md.stem}/; `fa storyline compile` makes one")
    return 0


def cmd_diff(args) -> int:
    sn = _snapshot_module()
    cm = _compile_module()
    md = _plan(args.plan)
    snaps = {d.name: d for d in sn.list_snapshots(ROOT, md)}
    if not snaps:
        print(f"no snapshots under outputs/storylines/{md.stem}/; `fa storyline compile` makes one")
        return 2
    names = list(snaps)
    revs = list(args.revisions)
    for r in revs:
        if r not in snaps and r != "current":
            print(f"unknown snapshot {r}; have: {', '.join(names)} (or 'current')")
            return 2
    if args.draft and not revs:
        revs = [names[-1], "current"]
    elif len(revs) == 1:
        revs = [revs[0], "current"]
    elif not revs:
        if len(names) < 2:
            print(f"only one snapshot ({names[0]}); compare it with the working state: "
                  f"`fa storyline diff {names[0]} current`")
            return 2
        revs = names[-2:]

    def load(r):
        if r == "current":
            story = cm.parse_storyline_md(md)
            return sn.current(ROOT, story["figures"], [t["file"] for t in story["tables"]], cm.find_figure_pdf)
        return sn.load(snaps[r])

    d = sn.diff(load(revs[0]), load(revs[1]))
    text = sn.render(d)
    if args.json:
        print(json.dumps(d, indent=1, ensure_ascii=False, default=str))
    else:
        print(text)
    if args.write and revs[1] != "current":
        out = cm.storyline_yaml_path(md).parent / "revisions" / f"{revs[1]}.changes.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
    if args.draft:
        import datetime
        rv = _revisions_module()
        latest = rv.report(rv.group(rv.extract_blocks(md)))["latest"]
        n = int(latest[1:]) + 1
        print("Suggested storyline entry (add the title and the reason, then compile and "
              "`fa storyline revisions --sync`):\n")
        word = "개편" if "개편(" in md.read_text(encoding="utf-8") else "Revision"
        print(sn.draft_block(d, n, datetime.date.today().isoformat(), word))
    return 0


