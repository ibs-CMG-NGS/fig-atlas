def cmd_revisions(args) -> int:
    rv = _revisions_module()
    md = _plan(args.plan)
    out_dir = _compile_module().storyline_yaml_path(md).parent / "revisions"
    names = {p.stem.removeprefix("config_") for p in (ROOT / "configs").rglob("config_*.yaml")}
    if args.sync:
        new, rep = rv.sync(md, out_dir, ROOT, names)
        print(f"{out_dir.relative_to(ROOT)}: {len(new)} new record(s), index rewritten")
    else:
        rep = rv.report(rv.group(rv.extract_blocks(md)))
    print(f"{md.name}: {rep['count']} revisions in {rep['blocks']} blocks; latest {rep['latest']}")
    if rep["gaps"]:
        print(f"  numbers never used: {', '.join(map(str, rep['gaps']))}")
    for n, titles in sorted(rep["collisions"].items()):
        print(f"  possible numbering collision, revision {n}: " + " | ".join(titles))
    if rep["multi_block"]:
        print(f"  logged in more than one place: {', '.join(map(str, rep['multi_block']))}")
    missing = [] if not out_dir.is_dir() else [
        n for n in rv.group(rv.extract_blocks(md)) if not (out_dir / f"R{n:03d}.md").exists()]
    if not out_dir.is_dir() or missing:
        print(f"  {len(missing) if missing else rep['count']} revision(s) have no record; run with --sync")
    return 0


