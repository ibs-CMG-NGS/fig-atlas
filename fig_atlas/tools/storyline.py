"""Storyline tools (roadmap Phase 3S, steps S.1-S.4).

A storyline's figure assignment -- which project fills which manuscript slot,
which supplementary tables it ships, which projects were retired -- lives in
``docs/storylines/<topic>/storyline.yaml`` (the single source; previously
hardcoded in compile_storyline_pdf.py). The narrative stays in
``docs/storylines/figure_plan_<topic>.md``.

    python scripts/storyline.py init      --plan docs/storylines/figure_plan_<topic>.md
    python scripts/storyline.py registry  [--plan ...]   # rewrite the md's Master Mapping Registry table
    python scripts/storyline.py check     [--plan ...]   # configs, specs, tasks.json, archive, registry
    python scripts/storyline.py revisions [--plan ...] [--sync]  # 개편(N) log -> revisions/RNNN.md records
    python scripts/storyline.py snapshots [--plan ...]           # compile snapshots (outputs/storylines/...)
    python scripts/storyline.py diff [A [B]] [--draft] [--write] # what changed between revisions
    python scripts/storyline.py requests  [--sync]                # data-request ledger (docs/data_contracts/)
    python scripts/storyline.py evidence  <slot|project>         # figure -> data -> requests -> revisions
    python scripts/storyline.py compile   [--plan ... | --all] [--strict]   # the A4 compendium PDF
    fa storyline ...                                     # same; `fa storyline --plan X` still compiles
"""
