def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0].startswith("--"):          # `fa storyline --plan X` / `--all`: compile, as before
        argv = ["compile", *argv]
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new", help="start a storyline: its storyline.yaml and plan document")
    p.add_argument("topic", help="short name, e.g. h2o2-atac (lower-case letters, digits, -)")
    p.add_argument("--title", help="title of the plan document (default: the topic)")
    p.add_argument("--narrative", help="one paragraph for the compendium cover")
    p = sub.add_parser("init", help="write storyline.yaml from the legacy (hardcoded) assignment")
    p.add_argument("--plan"); p.add_argument("--force", action="store_true")
    p = sub.add_parser("registry", help="rewrite the Master Mapping Registry table from storyline.yaml")
    p.add_argument("--plan")
    p = sub.add_parser("check", help="consistency of storyline.yaml with configs, specs, tasks.json, archive")
    p.add_argument("--plan")
    p = sub.add_parser("revisions", help="revision records (revisions/RNNN.md) from the md's 개편(N) log")
    p.add_argument("--plan"); p.add_argument("--sync", action="store_true", help="write missing records + index")
    p = sub.add_parser("snapshots", help="list compile snapshots (outputs/storylines/<storyline>/RNNN/)")
    p.add_argument("--plan")
    p = sub.add_parser("diff", help="what changed between two snapshots, or a snapshot and the working state")
    p.add_argument("revisions", nargs="*", metavar="REV",
                   help="two of RNNN | current (default: the last two snapshots; one REV = REV vs current)")
    p.add_argument("--plan"); p.add_argument("--json", action="store_true")
    p.add_argument("--write", action="store_true", help="save as revisions/<REV>.changes.md (second REV)")
    p.add_argument("--draft", action="store_true",
                   help="last snapshot vs working state, plus a suggested 개편(N) entry for the md")
    p = sub.add_parser("requests", help="data-request ledger (docs/data_contracts/*_request.md): status, use")
    p.add_argument("--sync", action="store_true", help="draft front matter for requests that have none")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("evidence", help="slot or project -> figure -> data read -> requests -> revisions")
    p.add_argument("target", help='a slot ("Main Figure 3") or a project name')
    p.add_argument("--plan"); p.add_argument("--json", action="store_true")
    sub.add_parser("compile", help="compile the compendium PDF (--plan FILE | --all)", add_help=False)
    if argv[0] == "compile":
        mod = _compile_module()
        sys.argv = ["compile_storyline_pdf.py", *argv[1:]]
        mod.main()
        return 0
    args = ap.parse_args(argv)
    return {"new": cmd_new, "init": cmd_init, "registry": cmd_registry, "check": cmd_check, "revisions": cmd_revisions,
            "snapshots": cmd_snapshots, "diff": cmd_diff, "requests": cmd_requests,
            "evidence": cmd_evidence}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
