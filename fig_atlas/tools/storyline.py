ROOT = project_root()
sys.path.insert(0, str(ROOT))

from fig_atlas.projects import ProjectError, find_project  # noqa: E402

DEFAULT_PLAN = None          # the repository's only storyline (tests may set a path)
REG_START, REG_END = "<!-- registry:start (generated by `fa storyline registry`; edit storyline.yaml instead) -->", \
    "<!-- registry:end -->"


def _compile_module():
    spec = importlib.util.spec_from_file_location("compile_storyline_pdf", Path(__file__).with_name("compile_storyline_pdf.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _plan(arg: str | None) -> Path:
    p = Path(arg) if arg else (DEFAULT_PLAN or _compile_module().default_storyline())
    return p if p.is_absolute() else ROOT / p


def _q(s) -> str:
    """A YAML-safe scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


# ----------------------------------------------------------------------- init --
def cmd_init(args) -> int:
    mod = _compile_module()
    md = _plan(args.plan)
    out = mod.storyline_yaml_path(md)
    if out.exists() and not args.force:
        print(f"{out.relative_to(ROOT)} exists; use --force to regenerate it from the legacy parser")
        return 1
    story = mod.parse_storyline_md(md, use_yaml=False)
    retired = sorted(p.name for p in find_archived())
    lines = [
        "# Storyline figure assignment -- the single source for which project fills",
        "# which manuscript slot. Read by the compendium compiler, the print audit,",
        "# fa preflight / baseline / inventory, and `fa storyline registry` (which",
        f"# writes the Master Mapping Registry table in {md.name}).",
        "# Change the storyline here; keep the narrative and revision log in the md.",
        f"storyline: {_q(md.stem.removeprefix('figure_plan_'))}",
        f"plan: {_q(md.relative_to(ROOT).as_posix())}",
        "",
        "# [Figures] Compendium order = manuscript order. slot: the label printed on",
        "# the page; project: bare project name (configs/**/config_<project>.yaml);",
        "# figure_number: which of the project's figures (figure_specs/**/figure_NN_<project>.py);",
        "# description: one line for the cover page's allocation table.",
        "figures:",
    ]
    for f in story["figures"]:
        lines += [f"  - slot: {_q(f['role'])}", f"    project: {_q(f['project'])}",
                  f"    figure_number: {int(f['figure_number'] or 1)}", f"    description: {_q(f['description'])}"]
    lines += ["", "# [Supplementary tables] CSV files under outputs/supplementary/, listed on the",
              "# cover page; generator: the script that writes the table.", "tables:"]
    for t in story["tables"]:
        lines += [f"  - slot: {_q(t['role'])}", f"    file: {_q(t['file'])}",
                  f"    generator: {_q(t['generator'])}", f"    description: {_q(t['description'])}"]
    lines += ["", "# [Retired] Former figures moved to <domain>/archive/ (AGENTS.md section 5.3);",
              "# listed in the registry table, never compiled.", "retired:"]
    lines += [f"  - {_q(r)}" for r in retired] or ["  []"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out.relative_to(ROOT)} ({len(story['figures'])} figures, {len(story['tables'])} tables, "
          f"{len(retired)} retired)")
    return 0


def find_archived() -> list[Path]:
    """Config files of retired projects (configs/<domain>/archive/)."""
    return [Path(p.stem.removeprefix("config_")) for p in sorted((ROOT / "configs").rglob("config_*.yaml"))
            if "archive" in p.relative_to(ROOT / "configs").parts]


# ------------------------------------------------------------------- registry --
def _link(md: Path, target: Path) -> str:
    rel = os.path.relpath(target, md.parent).replace("\\", "/")
    return f"[{target.name}]({rel})"


def _spec_file(project: str, number: int) -> Path | None:
    found = sorted((ROOT / "figure_specs").rglob(f"figure_{number:02d}_{project}.py"))
    return found[0] if found else None


def registry_table(md: Path, story: dict) -> list[str]:
    rows = ["| Manuscript Figure | Project Identifier (`<project_name>`) | Configuration (`configs/`) | "
            "Analysis Script (`analysis/`) | Primary Figure Spec (`figure_specs/`) | Status |",
            "| :--- | :--- | :--- | :--- | :--- | :---: |"]

    def cells(project: str, number: int) -> list[str]:
        try:
            p = find_project(ROOT, project)
        except ProjectError:
            return ["(missing config)", "(?)", "(?)"]
        script = ROOT / p.analysis_script if p.analysis_script else None
        spec = _spec_file(project, number)
        return [_link(md, p.config),
                _link(md, script) if script and script.is_file() else "(missing script)",
                _link(md, spec) if spec else "(missing spec)"]

    for f in story["figures"]:
        rows.append(f"| **{f['role']}** | `{f['project']}` | " + " | ".join(cells(f["project"], int(f["figure_number"] or 1)))
                    + f" | {f.get('status', 'Active')} |")
    for name in story.get("retired", []):
        rows.append(f"| *(Archived)* | `{name}` | " + " | ".join(cells(name, 1)) + " | Retired |")
    return rows


def _replace_registry(text: str, table: list[str]) -> str:
    block = "\n".join([REG_START, *table, REG_END])
    if REG_START in text and REG_END in text:
        a = text.index(REG_START)
        b = text.index(REG_END) + len(REG_END)
        return text[:a] + block + text[b:]
    # First run: replace the hand-written table under the registry heading.
    lines = text.split("\n")
    head = next(i for i, l in enumerate(lines) if "Master Figure-Project 1:1 Mapping Registry" in l)
    start = next(i for i in range(head + 1, len(lines)) if lines[i].startswith("| Manuscript Figure"))
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return "\n".join(lines[:start] + block.split("\n") + lines[end:])


def cmd_registry(args) -> int:
    mod = _compile_module()
    md = _plan(args.plan)
    story = mod.parse_storyline_md(md)
    text = md.read_text(encoding="utf-8")
    new = _replace_registry(text, registry_table(md, story))
    if new == text:
        print(f"{md.relative_to(ROOT)}: registry table already up to date")
    else:
        md.write_text(new, encoding="utf-8")
        print(f"{md.relative_to(ROOT)}: registry table rewritten from storyline.yaml")
    return 0


